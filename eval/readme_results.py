"""Write the README's results block from the results files, so the published numbers can't drift from the data.

    python -m eval.readme_results

Reads (nothing is recomputed here):
  results/listeners.json        per sound pair, the fine-tuned listener's margin rule = what the app runs for English
  results/match_listener_v1.json   the "did they read this sentence / this word?" checks for the same listener
Rewrites only the part of README.md between START and END; the rest of the README is left as it is.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
LISTENERS = ROOT / "results" / "listeners.json"
MATCH = ROOT / "results" / "match_listener_v1.json"

START = "<!-- results:start (generated by `python -m eval.readme_results`; edits here are overwritten) -->"
END = "<!-- results:end -->"

# target sound -> what was heard instead (the pair ids used across backend/ and eval/)
LABELS = {
    "r_as_l": "English R said as L",
    "l_as_r": "English L said as R",
    "f_as_p": "F said as P",
    "v_as_b": "V said as B",
    "th_as_s": "TH (as in *think*) said as S",
    "dh_as_d": "TH (as in *this*) said as D",
    "ih_as_iy": "short i (*ship*) said as long ee (*sheep*)",
    "iy_as_ih": "long ee (*sheep*) said as short i (*ship*)",
    "extra_vowel": "extra vowel after a final consonant (*bus-eu*)",
}


# ---------- formatting ----------
def _pct(v):
    """Decimals chosen per number, so rounding never hides a difference that matters: 1/1,070 isn't "0%",
    1.3% isn't "1%" next to a 0.5% cap, 598/600 isn't "100%"."""
    d = 2 if v < 0.01 else 1 if v < 0.10 or 0.90 < v < 1 else 0
    return f"{100 * v:.{d}f}"


def fmt(x):
    """'k/n (rate%; low–high%)', the count first so a reader sees how small n is."""
    if not x or not x.get("n") or x.get("rate") is None:
        return "—"
    s = f"{x['k']:,}/{x['n']:,} ({_pct(x['rate'])}%"
    if x.get("ci95"):
        lo, hi = x["ci95"]
        s += f"; {_pct(lo)}–{_pct(hi)}%"
    return s + ")"


# ---------- per sound pair ----------
def pair_rows(listeners):
    """One row per sound pair: the fine-tuned listener's margin rule (what the app runs), pairs in the app first."""
    rows = []
    for pair, r in listeners["pairs"].items():
        rule = r["new"]["margin rule"]
        test, base = rule["test (korean)"], rule["baseline (korean)"]
        p = test.get("precision")
        rows.append({
            "pair": pair,
            "label": LABELS[pair],
            "enabled": bool(rule.get("enabled")),
            "in_app": "yes" if rule.get("enabled") else "off (failed the bar)",
            "caught": fmt(test["caught"]),
            "false_alarms": fmt(test["false_alarms"]),
            "reds_right": "—" if p is None else f"{round(100 * p)}%",
            "baseline_caught": fmt(base["caught"]),
            "baseline_false_alarms": fmt(base["false_alarms"]),
        })
    return sorted(rows, key=lambda r: not r["enabled"])   # stable: keeps the file's order within each group


def _cap(listeners):
    caps = {r["new"]["margin rule"].get("cap") for r in listeners["pairs"].values()}
    caps.discard(None)
    return f"{100 * caps.pop():g}%" if len(caps) == 1 else "a per-pair cap"


# ---------- the whole block ----------
def render(listeners, match):
    en = match["en"]
    sent, word = en["sentence"]["test"], en["word"]["test"]
    caps = match["caps"]
    out = [
        START,
        "## Results: Korean speakers learning English",
        "",
        "All numbers are on **Korean speakers of English who were never used for training or tuning** "
        "(L2-ARCTIC, its suitcase corpus, and the Speech Accent Archive). Each cell is a count with a 95% "
        "interval. Small counts mean wide intervals. Everything the app reports about your pronunciation is "
        "estimated from audio.",
        "",
        "### Sound by sound",
        "",
        f"A sound check is on in the app only if, on these test speakers, at most {_cap(listeners)} of correctly "
        "said sounds get flagged, at least half of its red marks are real errors, and it catches at least one "
        "error. Thresholds are tuned on other speakers. **Baseline:** flag every sound the phoneme recognizer "
        "transcribes differently from the target (no confidence margin, no tuning).",
        "",
        "| Sound (target → heard) | In the app | Real errors caught | Correct sounds wrongly flagged "
        "| Red marks that were real errors | Baseline: caught | Baseline: wrongly flagged |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in pair_rows(listeners):
        out.append(f"| {r['label']} | {r['in_app']} | {r['caught']} | {r['false_alarms']} | {r['reds_right']} "
                   f"| {r['baseline_caught']} | {r['baseline_false_alarms']} |")
    out += [
        "",
        "### Did they read the sentence? Was each word said?",
        "",
        f"{sent['orig']['n']:,} readings by L2-ARCTIC's 4 Korean speakers, edited so the right answer is known: "
        "a word cut out of the audio, one word of the text swapped for another, the text of a different "
        "sentence, or silence/noise in place of speech.",
        "",
        f"| Sentence check (cap: {100 * caps['sentence']:g}% of correct readings rejected) | Result |",
        "|---|---|",
        f"| Correct readings wrongly rejected | {fmt(sent['orig'])} |",
        f"| Text of a different sentence: rejected | {fmt(sent['other'])} |",
        f"| Silence, noise or a beep: rejected | {fmt(sent['noise'])} |",
        f"| One word swapped: rejected (left to the word check) | {fmt(sent['swap'])} |",
        f"| One word cut out: rejected (left to the word check) | {fmt(sent['cut'])} |",
        "",
        f"| Word check (cap: {100 * caps['word']:g}% of spoken words called \"not heard\") | Result |",
        "|---|---|",
        f"| Words a human marked correct, wrongly called \"not heard\" | {fmt(word['false_not_heard_human_correct'])} |",
        f"| All spoken words, wrongly called \"not heard\" | {fmt(word['false_not_heard_all_words'])} |",
        f"| A word cut out of the audio: caught | {fmt(word['caught_cut'])} |",
        f"| A word swapped in the text: caught | {fmt(word['caught_swap'])} |",
        "",
        "Processing time per sentence: not yet measured for this listener.",
        "",
        "Korean (English speakers learning Korean): the sound checks are off. No learner Korean with "
        "sound-by-sound error labels was available to tune and test them safely.",
        END,
    ]
    return "\n".join(out) + "\n"


def update_readme(text, block):
    """Replace the block between the markers; with no markers yet, put it right after the title line."""
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        return head + block.rstrip("\n") + tail
    title, sep, body = text.partition("\n")
    return title + "\n\n" + block + ("\n" + body.lstrip("\n") if body.strip() else "")


def main():
    block = render(json.loads(LISTENERS.read_text()), json.loads(MATCH.read_text()))
    README.write_text(update_readme(README.read_text(), block))
    print(f"wrote the results block in {README.relative_to(ROOT)} ({block.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
